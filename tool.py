#!/usr/bin/env python3
"""Identify inode exhaustion separately from byte capacity."""
import argparse
import collections
import configparser
import datetime
import fnmatch
import hashlib
import ipaddress
import itertools
import json
import math
import re
import statistics
import sys
import urllib.parse


def evaluate(data):
    """Evaluate supplied infrastructure metadata without changing remote systems."""
    if not isinstance(data, dict):
        raise ValueError("input must be a JSON object")
    rows = []
    threshold = float(data.get('threshold_percent', 85))
    if not 0 <= threshold <= 100:
        raise ValueError('threshold must be 0-100')
    for fs in data['filesystems']:
        total, used = int(fs['total_inodes']), int(fs['used_inodes'])
        if total <= 0 or not 0 <= used <= total:
            raise ValueError('invalid inode counts')
        percentage = round(used/total*100, 2)
        rows.append({'mount':fs['mount'], 'used_percent':percentage, 'alert':percentage >= threshold})
    return {'filesystems': rows}


def _check_finite(value):
    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError("numeric input must be finite")
    if isinstance(value, dict):
        for child in value.values():
            _check_finite(child)
    elif isinstance(value, list):
        for child in value:
            _check_finite(child)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", nargs="?", default="-", help="JSON input file, or - for stdin")
    args = parser.parse_args(argv)
    try:
        if args.input == "-":
            data = json.load(sys.stdin)
        else:
            with open(args.input, encoding="utf-8") as source:
                data = json.load(source)
        _check_finite(data)
        result = evaluate(data)
        print(json.dumps(result, indent=2, sort_keys=True, allow_nan=False))
        return 0
    except (OSError, ValueError, TypeError, KeyError, OverflowError, configparser.Error) as error:
        print("Input error: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
